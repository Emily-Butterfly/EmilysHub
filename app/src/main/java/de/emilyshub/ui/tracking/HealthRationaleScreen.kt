/**
 * Why Tracking reads Health Connect, as Health Connect asks the app to show (SPEC.md §17): only to read, only while
 * Tracking is open, and nothing leaves the phone. Only this text: nothing of Tracking shows here.
 */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
internal fun HealthRationaleScreen(onBack: () -> Unit) {
    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text(stringResource(R.string.health_rationale_title), modifier = Modifier.semantics { heading() }) },
                navigationIcon = {
                    IconButton(onClick = onBack) {
                        Icon(Icons.AutoMirrored.Filled.ArrowBack, contentDescription = stringResource(R.string.navigate_back))
                    }
                },
            )
        },
    ) { contentPadding ->
        Column(
            Modifier
                .fillMaxSize()
                .padding(contentPadding)
                .verticalScroll(rememberScrollState())
                .padding(16.dp),
            verticalArrangement = Arrangement.spacedBy(12.dp),
        ) {
            Text(stringResource(R.string.health_rationale_text))
        }
    }
}
